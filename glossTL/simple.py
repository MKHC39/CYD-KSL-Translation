import re

text = """
**41.** 바다에서 멀리 떨어진 지역에 대한 바람 주의보가 오늘 종료되었습니다.

**42.** 오늘 아침 9시 10분, 운연 지역 산(고도 634m)과 백두한양 아파트 주변에서 산불이 발생했습니다. 인근 북쪽은 안전하니 해당 장소를 빠르게 대피해 주십시오.

**43.** 남쪽 지역에서는 낮 최고 기온이 -3 °C에서 7 °C 사이이며, 아침 최저 기온은 -14 °C에서 -1 °C로 떨어질 전망입니다.

**44.** 오늘 저녁 5시 30분에 전남 장흥과 경북 포항 지역에서 비가 내리면서 산과 지면이 여러 차례 침수되고 있습니다. 해당 장소는 위험하므로 외출을 삼가고 주의하시기 바랍니다.

**45.** 2021년 1월 6일 저녁 5시, 웅진 지역과 서해 도로 주변에서 바람이 불어올 예정입니다. 배를 잠그고 묶어 두며 시설은 사고가 없으나 주의하시기 바랍니다.

**46.** 오늘 오후 1시 45분에 광주 지역 초월·월정 지역 498번길(하이픈 5)에서 한 차선으로 진행되는 차량 사고가 발생해 해당 장소 근처에 위험이 있습니다.

**47.** 오늘 낮 12시, 감천 지역 아래 땅에서 산불이 발생했습니다. 해당 구역에서는 차량 운행을 금지하고 주의를 부탁드립니다.
"""

entries = re.split(r"\n\s*\n", text.strip())

cleaned = []
for entry in entries:
    entry = entry.strip()

    # 1) Strip Markdown bold numbering like "**1.** "
    entry = re.sub(r"^\s*\*\*\s*\d+\s*[\.\)\-]\s*\*\*\s*", "", entry)

    # 2) Strip plain numbering like "1. ", "10)", "3 - "
    entry = re.sub(r"^\s*\d+\s*[\.\)\-]\s*", "", entry)

    cleaned.append(entry)

print("\n".join(cleaned))
